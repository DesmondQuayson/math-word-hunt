import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

const REPOSITORY = 'DesmondQuayson/math-word-hunt';
const BRANCH = 'seo-reports';
const MAX_REPORT_BYTES = 500_000;

export function validatePublicReport(report) {
  if (report?.schemaVersion !== 1 || report.kind !== 'mathnexa-public-seo' || report.publicDataOnly !== true || report.mode !== 'live') {
    throw new Error('Only live public SEO reports can be published');
  }
  if (!report.audit || !Array.isArray(report.audit.sites) || !Array.isArray(report.proposals) || !Array.isArray(report.ledger)) throw new Error('Invalid report structure');
  if (Buffer.byteLength(JSON.stringify(report)) > MAX_REPORT_BYTES) throw new Error('Report exceeds public storage limit');
  return report;
}

export function githubClient({ token, fetchImpl = globalThis.fetch } = {}) {
  if (!token) throw new Error('GitHub workflow token is required');
  return async (path, { method = 'GET', body, allow404 = false } = {}) => {
    if (!/^\/(?:git\/|contents\/|$)/.test(path)) throw new Error('GitHub endpoint outside report scope');
    // GitHub's repository endpoint does not accept a trailing slash.
    const response = await fetchImpl(`https://api.github.com/repos/${REPOSITORY}${path === '/' ? '' : path}`, {
      method, redirect: 'error', signal: AbortSignal.timeout(20_000),
      headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2026-03-10', 'Content-Type': 'application/json' },
      ...(body ? { body: JSON.stringify(body) } : {})
    });
    if (allow404 && response.status === 404) return null;
    if (!response.ok) throw new Error(`GitHub report operation failed (HTTP ${response.status})`);
    const text = await response.text();
    if (Buffer.byteLength(text) > 2_000_000) throw new Error('GitHub response exceeded limit');
    return JSON.parse(text);
  };
}

export async function restoreState(api, output) {
  const ref = await api(`/git/ref/heads/${BRANCH}`, { allow404: true });
  await mkdir(output, { recursive: true });
  if (!ref) return false;
  const file = await api(`/contents/reports/latest.json?ref=${ref.object.sha}`);
  if (file.encoding !== 'base64' || file.size > MAX_REPORT_BYTES) throw new Error('Invalid previous report encoding or size');
  const text = Buffer.from(file.content, 'base64').toString('utf8');
  validatePublicReport(JSON.parse(text));
  await writeFile(join(output, 'previous.json'), text);
  // Carry the exact parent through the entire run to detect concurrent writers.
  await writeFile(join(output, 'parent.txt'), `${ref.object.sha}\n`);
  return true;
}

export async function publishState(api, { output, runId, attempt, expectedParent = null }) {
  if (!/^\d+$/.test(runId) || !/^\d+$/.test(attempt)) throw new Error('A verified GitHub run identity is required');
  const reportText = await readFile(join(output, 'report.json'), 'utf8');
  validatePublicReport(JSON.parse(reportText));
  const markdown = await readFile(join(output, 'report.md'), 'utf8');
  if (Buffer.byteLength(markdown) > MAX_REPORT_BYTES) throw new Error('Report summary exceeded limit');
  const ref = await api(`/git/ref/heads/${BRANCH}`, { allow404: true });
  if ((ref?.object.sha ?? null) !== expectedParent) throw new Error('Report branch changed during execution; rerun to reconcile');
  const parent = ref ? await api(`/git/commits/${ref.object.sha}`) : null;
  const files = [
    { path: 'README.md', content: '# MathNexa public SEO evidence\n\nGenerated by .github/workflows/mathnexa-seo.yml. Public-page checks only.\n\nSee reports/latest.md and reports/latest.json. Git history preserves previous runs. No analytics exports, customer data, or secrets belong here.\n' },
    { path: 'reports/latest.json', content: reportText },
    { path: 'reports/latest.md', content: markdown }
  ];
  const tree = await api('/git/trees', { method: 'POST', body: {
    ...(parent ? { base_tree: parent.tree.sha } : {}),
    tree: files.map(file => ({ ...file, mode: '100644', type: 'blob' }))
  } });
  const commit = await api('/git/commits', { method: 'POST', body: {
    message: `Public SEO check ${runId} attempt ${attempt}`, tree: tree.sha, parents: ref ? [ref.object.sha] : []
  } });
  if (ref) await api(`/git/refs/heads/${BRANCH}`, { method: 'PATCH', body: { sha: commit.sha, force: false } });
  else await api('/git/refs', { method: 'POST', body: { ref: `refs/heads/${BRANCH}`, sha: commit.sha } });
  const verified = await api(`/git/ref/heads/${BRANCH}`);
  if (verified.object.sha !== commit.sha) throw new Error('Remote report commit could not be verified');
  return commit.sha;
}

async function main() {
  const { values } = parseArgs({ options: { mode: { type: 'string' }, output: { type: 'string', default: '.seo-output' } } });
  if (process.env.GITHUB_REPOSITORY !== REPOSITORY || process.env.GITHUB_ACTIONS !== 'true') throw new Error('Run this only in the configured GitHub-hosted workflow');
  const api = githubClient({ token: process.env.GH_TOKEN });
  const repository = await api('/');
  if (repository.private || repository.full_name !== REPOSITORY) throw new Error('Cloud workflow requires the verified public repository');
  const output = resolve(values.output);
  if (values.mode === 'restore') {
    console.log(await restoreState(api, output) ? 'Previous public report restored.' : 'First run: no previous report branch.');
  } else if (values.mode === 'publish') {
    let expectedParent = null;
    try { expectedParent = (await readFile(join(output, 'parent.txt'), 'utf8')).trim(); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
    const commit = await publishState(api, { output, expectedParent, runId: process.env.GITHUB_RUN_ID ?? '', attempt: process.env.GITHUB_RUN_ATTEMPT ?? '' });
    console.log(`Verified public report commit ${commit} on ${BRANCH}.`);
  } else throw new Error('Use --mode restore or --mode publish');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(() => { console.error('GitHub report persistence failed. No force push was attempted; inspect workflow permissions and report-branch state.'); process.exitCode = 1; });
}
