#!/usr/bin/env node
/**
 * Solves the rope-grip fist of every Math Tug of War 3D character (both hands)
 * and writes them to the runtime's fist-data.js.
 *
 * Serves the shipped game with the mobile gameplay harness, opens it in
 * Chromium, loads the character document and runs grip.js's optimizeFist()
 * for each hand: the rope's channel through the palm is searched for the
 * placement whose closed fist (fingers and thumb wrapped round the rope until
 * the skin touches it) covers the most of the rope's circumference. The game
 * then loads these fists instead of solving them while it starts; it re-solves
 * a hand at runtime only if the models change and no longer match the stored
 * fingerprint. Run it again after regenerating the characters.
 *
 *   node scripts/math-tug-of-war-3d/solve-fists.mjs [--check]
 *
 *   --check   solve and compare with the committed file; exit 1 if they differ
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const require = createRequire(join(root, "package.json"));
const { chromium } = require("@playwright/test");
const { startMobileGameplayHarness } = await import(pathToFileURL(join(root, "scripts/mobile-gameplay-harness.mjs")).href);
const target = join(root, "apps/platform-web/public/internal-games/math-tug-of-war/src/scene3d/fist-data.js");
const check = process.argv.includes("--check");

const server = await startMobileGameplayHarness(0);
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true });
let solved;
try {
  const page = await browser.newPage();
  await page.goto(`${base}/games/math-tug-of-war/play`);
  solved = await page.evaluate(async () => {
    const root = "/internal-games/math-tug-of-war/src/scene3d/";
    const { CHARACTER_NAMES, ROPE_RADIUS } = await import(`${root}constants.js`);
    const { loadCharacters, instantiateCharacter } = await import(`${root}assets.js`);
    const { Rig } = await import(`${root}rig.js`);
    const { optimizeFist, fistToData } = await import(`${root}grip.js`);
    await loadCharacters("");
    const out = {};
    for (const name of CHARACTER_NAMES) {
      const instance = instantiateCharacter(name, {});
      const rig = new Rig(instance.root);
      rig.reset();
      const body = instance.meshes.find((mesh) => mesh.isSkinnedMesh && /body/i.test(mesh.name));
      out[name] = {};
      for (const side of ["Left", "Right"]) {
        const result = optimizeFist(rig, body, side, ROPE_RADIUS);
        if (!result) throw new Error(`no fist for ${name} ${side}`);
        if (!result.fist.metrics.closed) throw new Error(`${name} ${side}: no placement closes every digit round the rope`);
        out[name][side] = { ...fistToData(result.fist, result.fingerprint), placement: result.fist.metrics.placement };
      }
    }
    return out;
  });
} finally {
  await browser.close();
  server.close();
}

const lines = [
  "// GENERATED by scripts/math-tug-of-war-3d/solve-fists.mjs — do not edit by hand.",
  "// Each character's rope-grip fists (see grip.js): the rope's channel through the",
  "// hand and the finger/thumb joint rotations (bone-local quaternions) that wrap",
  "// the skin round it. `fingerprint` (hand-space knuckle positions) ties a fist to",
  "// the model it was solved for; `coverage` is the share of the rope's",
  "// circumference the closed hand covers.",
  "",
  `export const FIST_DATA = Object.freeze(${JSON.stringify(solved, null, 2)});`,
  ""
];
const text = lines.join("\n");
const summary = Object.entries(solved).map(([name, sides]) => `${name}: L ${sides.Left.coverage.toFixed(2)} R ${sides.Right.coverage.toFixed(2)}`).join("\n");
if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    current = "";
  }
  console.log(summary);
  if (current !== text) {
    console.error("fist-data.js is out of date: run node scripts/math-tug-of-war-3d/solve-fists.mjs");
    process.exit(1);
  }
  console.log("fist-data.js is up to date");
} else {
  writeFileSync(target, text);
  console.log(summary);
  console.log(`wrote ${target}`);
}
