#!/usr/bin/env node
/**
 * Builds the vendored three.js bundle used by the Math Tug of War 3D scene:
 *
 *   apps/platform-web/public/internal-games/math-tug-of-war/src/vendor/three.js
 *
 * three.js is MIT (Copyright © 2010-2026 three.js authors). Only the classes
 * listed in three-entry.js are kept (tree-shaken, minified, one ES module,
 * no dynamic imports, no workers, no eval), so the game's strict CSP
 * (`script-src 'self'`, `worker-src 'none'`) is honoured as-is.
 *
 *   npm ci && npm run bundle:three        (inside scripts/math-tug-of-war-3d)
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "vite";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const outDir = resolve(root, "apps/platform-web/public/internal-games/math-tug-of-war/src/vendor");
const version = JSON.parse(readFileSync(resolve(here, "node_modules/three/package.json"), "utf8")).version;
const license = readFileSync(resolve(here, "node_modules/three/LICENSE"), "utf8").trim().split("\n").map((line) => ` * ${line}`.trimEnd()).join("\n");

await build({
  root: here,
  logLevel: "warn",
  configFile: false,
  build: {
    lib: { entry: resolve(here, "three-entry.js"), formats: ["es"], fileName: () => "three.js" },
    outDir: resolve(here, "dist"),
    emptyOutDir: true,
    minify: true,
    target: "es2022",
    sourcemap: false,
    rollupOptions: { output: { inlineDynamicImports: true } }
  }
});

const built = readFileSync(resolve(here, "dist/three.js"), "utf8");
const header = `/**\n * three.js r${version} — subset bundle for MathNexa Math Tug of War (MIT).\n * Generated by scripts/math-tug-of-war-3d/bundle-three.mjs; do not edit.\n${license}\n */\n`;
mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "three.js"), header + built);
console.log(`three.js r${version} → ${resolve(outDir, "three.js")} (${(header.length + built.length) / 1024 | 0} KB)`);
